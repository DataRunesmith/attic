import test from "node:test";
import assert from "node:assert/strict";
import { existsSync, mkdtempSync, mkdirSync, readFileSync, rmSync, symlinkSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { spawnSync } from "node:child_process";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const renderer = join(root, "tools", "render.mjs");
const declared = [...readFileSync(join(root, "cloudflare.example.env"), "utf8")
  .matchAll(/^([A-Z][A-Z0-9_]*)=/gm)].map((m) => m[1]);

/** Run the renderer against isolated test values and an optional overlay fixture. */
function run(values, out, overlay, buildOutput = false) {
  const dir = mkdtempSync(join(tmpdir(), "attic-render-test-"));
  try {
    const envFile = join(dir, "values.env");
    writeFileSync(envFile, declared.map((name) => name + "=" + (values?.[name] ?? "test-value")).join("\n") + "\n");
    const args = [renderer, envFile, out, ...(overlay ? [overlay] : []), ...(buildOutput ? ["--build"] : [])];
    return spawnSync(process.execPath, args, { cwd: root, encoding: "utf8" });
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

test("renderer builds a complete Worker before committing staged output", () => {
  const dir = mkdtempSync(join(tmpdir(), "attic-render-build-"));
  const out = join(dir, "rendered");
  const values = {
    PUBLIC_HOST: "images.example.com",
    PUBLIC_ORIGIN: "https://images.example.com",
    GALLERY_BUCKET: "gallery",
    LEGACY_BUCKET: "legacy",
    SECRETS_STORE_ID: "b".repeat(32),
    CLOUDFLARE_ACCOUNT_ID: "a".repeat(32),
  };
  try {
    const result = run(values, out, undefined, true);
    assert.equal(result.status, 0, result.stderr);
    const worker = join(out, "dist", "worker.js");
    assert.equal(existsSync(worker), true);
    assert.match(readFileSync(worker, "utf8"), /PUBLIC_ORIGIN: "https:\/\/images\.example\.com"/);
    const syntax = spawnSync(process.execPath, ["--check", worker], { cwd: out, encoding: "utf8" });
    assert.equal(syntax.status, 0, syntax.stderr);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});

test("failed staged Worker builds preserve the previous rendered output", () => {
  const dir = mkdtempSync(join(tmpdir(), "attic-render-rollback-"));
  const out = join(dir, "rendered");
  mkdirSync(out);
  writeFileSync(join(out, ".attic-render-output"), "Generated by tools/render.mjs. Safe to replace.\n");
  writeFileSync(join(out, "previous.txt"), "keep previous output");
  const values = {
    PUBLIC_HOST: "invalid host",
    PUBLIC_ORIGIN: "https://images.example.com",
    GALLERY_BUCKET: "gallery",
    LEGACY_BUCKET: "legacy",
    SECRETS_STORE_ID: "b".repeat(32),
    CLOUDFLARE_ACCOUNT_ID: "a".repeat(32),
  };
  try {
    const result = run(values, out, undefined, true);
    assert.notEqual(result.status, 0);
    assert.equal(readFileSync(join(out, "previous.txt"), "utf8"), "keep previous output");
    assert.equal(existsSync(join(out, "dist", "worker.js")), false);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});

test("renderer refuses to target the source tree or its parent", () => {
  const parent = resolve(root, "..");
  const sourceResult = run({}, root);
  assert.notEqual(sourceResult.status, 0);
  assert.match(sourceResult.stderr, /Output directory cannot be the source/);
  const parentResult = run({}, parent);
  assert.notEqual(parentResult.status, 0);
  assert.match(parentResult.stderr, /Output directory cannot be the source/);
});

test("renderer refuses an output symlink without touching its target", () => {
  const dir = mkdtempSync(join(tmpdir(), "attic-render-link-"));
  const target = join(dir, "target");
  const out = join(dir, "rendered");
  mkdirSync(target);
  writeFileSync(join(target, "keep.txt"), "must remain");
  symlinkSync(target, out, "dir");
  try {
    const result = run({}, out);
    assert.notEqual(result.status, 0);
    assert.equal(readFileSync(join(target, "keep.txt"), "utf8"), "must remain");
    assert.equal(existsSync(out), true);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});

test("renderer never deletes an existing directory it does not own", () => {
  const dir = mkdtempSync(join(tmpdir(), "attic-render-unsafe-"));
  const out = join(dir, "important");
  mkdirSync(out);
  const sentinel = join(out, "keep.txt");
  writeFileSync(sentinel, "must survive");
  try {
    const result = run({}, out);
    assert.notEqual(result.status, 0);
    assert.match(result.stderr, /not created by this renderer/);
    assert.equal(readFileSync(sentinel, "utf8"), "must survive");
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});

test("renderer escapes placeholder values as JSON string contents", () => {
  const dir = mkdtempSync(join(tmpdir(), "attic-render-json-"));
  const out = join(dir, "rendered");
  const injected = 'images.example.com","unexpected":true,"tail":"';
  try {
    const result = run({ PUBLIC_HOST: injected }, out);
    assert.equal(result.status, 0, result.stderr);
    const config = JSON.parse(readFileSync(join(out, "wrangler.jsonc"), "utf8"));
    assert.equal(config.routes[0].pattern, injected);
    assert.equal(config.routes[0].unexpected, undefined);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});

test("renderer excludes local env files and credential material from source and overlay", () => {
  const dir = mkdtempSync(join(tmpdir(), "attic-render-secret-"));
  const out = join(dir, "rendered");
  const overlay = join(dir, "overlay");
  mkdirSync(overlay);
  for (const [name, contents] of [
    [".envrc", "ADMIN_PASSWORD=must-not-copy\\n"],
    ["id_rsa", "private-key-material\\n"],
    ["id_ed25519", "private-key-material\\n"],
    ["service.pem", "private-key-material\\n"],
    ["notes.txt", "-----BEGIN OPENSSH PRIVATE KEY-----\\nsecret material\\n"],
    ["app.txt", "safe overlay file\\n"],
  ]) writeFileSync(join(overlay, name), contents, { flag: "wx" });
  try {
    const result = run({}, out, overlay);
    assert.equal(result.status, 0, result.stderr);
    assert.equal(readFileSync(join(out, "README.md"), "utf8").length > 0, true);
    assert.equal(readFileSync(join(out, "app.txt"), "utf8"), "safe overlay file\\n");
    for (const name of [".envrc", "id_rsa", "id_ed25519", "service.pem", "notes.txt"])
      assert.equal(existsSync(join(out, name)), false, name + " must not be rendered");
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});

test("a failed staged render leaves the previous owned output intact", () => {
  const dir = mkdtempSync(join(tmpdir(), "attic-render-atomic-"));
  const out = join(dir, "rendered");
  const overlay = join(dir, "overlay");
  mkdirSync(overlay);
  try {
    const first = run({}, out);
    assert.equal(first.status, 0, first.stderr);
    const sentinel = join(out, "README.md");
    const original = readFileSync(sentinel, "utf8");
    // Symlinks are rejected during staging, before the old output is moved.
    symlinkSync(join(dir, "missing-target"), join(overlay, "unsafe-link"));
    const failed = run({}, out, overlay);
    assert.notEqual(failed.status, 0);
    assert.equal(readFileSync(sentinel, "utf8"), original);
    assert.equal(existsSync(join(out, ".attic-render-output")), true);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});

